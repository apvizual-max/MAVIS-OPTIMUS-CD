# jules_repo_scanner.ps1 — Antigravity Fleet Scanner for Jules & GitHub Repos
[CmdletBinding()]
param(
    [string]$Owner = "apvizual-max",
    [string]$ReportPath = "C:\Users\apviz\Documents\Antigravity_Folder\Antigravity_Projects\Antigravity_JULES_INT\reports\FLEET_STATUS_REPORT.md"
)

Write-Host "=== Antigravity Jules Fleet Scanner ===" -ForegroundColor Cyan
Write-Host "Target Account: $Owner" -ForegroundColor Yellow

$reposJson = gh repo list $Owner --limit 50 --json name,isPrivate,defaultBranchRef,updatedAt 2>$null
if (-not $reposJson) {
    Write-Error "Failed to fetch repository list from GitHub CLI. Check 'gh auth status'."
    return
}

$repos = $reposJson | ConvertFrom-Json
$timestamp = (Get-Date).ToString("yyyy-MM-dd HH:mm:ss")

$reportContent = @()
$reportContent += "# Antigravity Jules Fleet Status Report"
$reportContent += ""
$reportContent += "**Generated:** $timestamp  "
$reportContent += "**Account:** `$Owner`  "
$reportContent += "**Scan Policy:** Single-Branch Invariant (`main` as eternal baseline)  "
$reportContent += ""
$reportContent += "| Repository | Visibility | Default Branch | Open PRs | Jules PRs | Non-Main Branches | JULES_HANDOFF.md |"
$reportContent += "|---|---|---|---|---|---|---|"

$totalOpenPRs = 0
$totalJulesPRs = 0
$totalStaleBranches = 0

foreach ($repo in $repos) {
    $rName = $repo.name
    $fullName = "$Owner/$rName"
    $defaultBranch = if ($repo.defaultBranchRef) { $repo.defaultBranchRef.name } else { "main" }
    $vis = if ($repo.isPrivate) { "Private" } else { "Public" }
    
    Write-Host "Scanning $fullName..." -ForegroundColor Gray
    
    # Check open PRs
    $openPRs = @()
    $prsRaw = gh pr list --repo $fullName --state open --limit 50 --json number,title,headRefName,createdAt 2>$null
    if ($prsRaw) {
        $openPRs = $prsRaw | ConvertFrom-Json
    }
    $prCount = if ($openPRs) { @($openPRs).Count } else { 0 }
    $totalOpenPRs += $prCount
    
    $julesPRCount = 0
    if ($openPRs) {
        $julesPRs = @($openPRs) | Where-Object { 
            $_.headRefName -match "jules|sentinel|palette|bolt|fix-|test-|perf-|code-health" -or 
            $_.title -match "Jules|Sentinel|Palette|Bolt|Code Health|Test"
        }
        $julesPRCount = if ($julesPRs) { @($julesPRs).Count } else { 0 }
    }
    $totalJulesPRs += $julesPRCount
    
    # Check remote branches
    $branchesJson = gh api "repos/$fullName/branches" --paginate --jq ".[].name" 2>$null
    $nonMainBranches = if ($branchesJson) {
        @($branchesJson) | Where-Object { $_ -ne "main" -and $_ -ne "master" -and -not [string]::IsNullOrWhiteSpace($_) }
    } else {
        @()
    }
    $branchCount = if ($nonMainBranches) { @($nonMainBranches).Count } else { 0 }
    $totalStaleBranches += $branchCount
    
    # Check JULES_HANDOFF.md existence
    $hasHandoff = "Missing"
    $null = gh api "repos/$fullName/contents/JULES_HANDOFF.md" 2>$null
    if ($LASTEXITCODE -eq 0) {
        $hasHandoff = "Present"
    }
    
    $reportContent += "| `$($rName)` | $vis | `$($defaultBranch)` | $prCount | $julesPRCount | $branchCount | $hasHandoff |"
}

$reportContent += ""
$reportContent += "### Executive Summary"
$reportContent += "- **Total Repositories Scanned:** $($repos.Count)"
$reportContent += "- **Total Open PRs:** $totalOpenPRs"
$reportContent += "- **Total Jules-generated PRs:** $totalJulesPRs"
$reportContent += "- **Total Non-Main (Stale) Branches:** $totalStaleBranches"
$reportContent += ""
$reportContent += "---"
$reportContent += "*Report generated by Antigravity Autonomous CD Engine.*"

$reportDir = Split-Path $ReportPath -Parent
if (-not (Test-Path $reportDir)) { New-Item -ItemType Directory -Path $reportDir -Force | Out-Null }
$reportContent -join "`n" | Out-File -FilePath $ReportPath -Encoding utf8 -Force

Write-Host "Report saved to $ReportPath" -ForegroundColor Green
Write-Host "Total Repos: $($repos.Count) | Open PRs: $totalOpenPRs | Jules PRs: $totalJulesPRs | Stale Branches: $totalStaleBranches" -ForegroundColor Yellow
